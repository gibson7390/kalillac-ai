"""Write every document-quality benchmark file to a folder, for a person to open and judge.

The benchmark (tests/quality_benchmark.py, and the report in tests/test_document_design.py) holds
realistic professional tasks. This tool produces each one in the formats it is meant for, plus the
edited versions, and a README listing what each file is. Nothing here is a quality score: whether
the files are good enough is the owner's judgement.

Usage (from candidate/):  python tools/render_benchmark.py OUTPUT_FOLDER
The folder is created if needed; existing files with the same names are replaced.
"""
from __future__ import annotations

import copy
from pathlib import Path
import sys
import time

CANDIDATE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CANDIDATE))
sys.path.insert(0, str(CANDIDATE / "tests"))

import quality_benchmark as benchmark  # noqa: E402
from kalillac_files import generate  # noqa: E402
from kalillac_files.editing import edit, outline  # noqa: E402
from test_document_design import ARABIC, REPORT  # noqa: E402

ARABIC_DECK = {
    "title": "خطة النمو ٢٠٢٧", "language": "ar", "organization": "شركة نورثويند للقهوة", "author": "دانة وايتفيلد",
    "date": "ديسمبر ٢٠٢٦",
    "slides": [
        {"layout": "title", "title": "خطة النمو ٢٠٢٧: من محمصة واحدة إلى اثنتين",
         "subtitle": "لماذا نضاعف الطاقة الإنتاجية، وكيف سنفعل ذلك"},
        {"layout": "metrics", "title": "أقوى عام في تاريخنا",
         "metrics": [{"label": "الإيرادات", "value": "$18.4M", "detail": "23% مقارنة بعام 2025", "trend": "up"},
                     {"label": "هامش الربح", "value": "41.6%", "detail": "2.1 نقطة", "trend": "up"},
                     {"label": "المشتركون", "value": "31,200", "detail": "18%", "trend": "up"}]},
        {"layout": "table", "title": "البناء يتفوق في كل مقياس", "header": ["المقياس", "البناء", "الاستعانة"],
         "rows": [["رأس المال المطلوب", "$4.2M", "$0"], ["هامش الربح", "41%", "32%"]]},
        {"layout": "closing", "title": "نطلب من المجلس الموافقة على الخطة"}]}

ENTRIES = [
    ("01-business-report", "Annual business review: cover, contents, metrics, charts, tables, callouts.",
     REPORT, ("pdf", "docx")),
    ("02-research-document", "Field-experiment report in the editorial theme: justified serif text, "
     "results tables and charts, references.", benchmark.RESEARCH_DOCUMENT, ("pdf", "docx")),
    ("03-financial-workbook", "Three-year operating forecast: inputs, monthly forecast, summary, loan "
     "schedule and dashboard, all live cross-sheet formulas.", benchmark.FORECAST_WORKBOOK, ("xlsx",)),
    ("04-word-proposal", "Client proposal on US Letter: goals, approach, timeline, fixed fees, guarantee.",
     benchmark.WORD_PROPOSAL, ("docx", "pdf")),
    ("05-executive-presentation", "Fourteen-slide board deck with native charts, a table and speaker notes.",
     benchmark.EXECUTIVE_DECK, ("pptx",)),
    ("07-multilingual-document", "Guest information in English, Spanish, Arabic, Japanese, Hindi and Russian.",
     benchmark.MULTILINGUAL_DOCUMENT, ("pdf", "docx")),
    ("08-arabic-report", "A right-to-left report.", ARABIC, ("pdf", "docx")),
    ("09-arabic-presentation", "A right-to-left deck.", ARABIC_DECK, ("pptx",)),
]


def main(argv):
    if len(argv) != 1:
        sys.exit(__doc__)
    folder = Path(argv[0])
    folder.mkdir(parents=True, exist_ok=True)
    lines = ["Kalillac document-quality benchmark", "",
             "Generated by candidate/tools/render_benchmark.py. Content is synthetic. These files are for the",
             "owner's review; none has been accepted by the owner.", ""]
    for stem, description, spec, formats in ENTRIES:
        for extension in formats:
            started = time.perf_counter()
            data = generate(copy.deepcopy(spec), extension).data
            (folder / f"{stem}.{extension}").write_bytes(data)
            lines.append(f"{stem}.{extension}  ({len(data) / 1024:,.0f} KB, {time.perf_counter() - started:.1f} s)")
        lines.append(f"    {description}")
        lines.append("")

    # 06: a complex edit of an existing file, kept beside the original.
    report = generate(copy.deepcopy(REPORT), "docx").data
    (folder / "06-complex-edit-original.docx").write_bytes(report)
    tracked = edit(report, "business-report.docx", benchmark.report_edit(outline(report, "business-report.docx")),
                   track_changes=True)
    (folder / "06-complex-edit-tracked.docx").write_bytes(tracked.data)
    workbook = generate(copy.deepcopy(benchmark.FORECAST_WORKBOOK), "xlsx").data
    edited = edit(workbook, "forecast.xlsx", benchmark.WORKBOOK_EDIT)
    (folder / "06-complex-edit-forecast.xlsx").write_bytes(edited.data)
    lines += ["06-complex-edit-original.docx, 06-complex-edit-tracked.docx",
              "    The business report restated after an audit, as Word tracked changes by \"Kalillac AI\": figures",
              "    replaced, a paragraph inserted, a table row added. Accept or reject each change in Word.",
              "06-complex-edit-forecast.xlsx",
              "    The forecast with customers at launch changed from 1,200 to 1,500; every dependent figure,",
              "    chart and dashboard tile is recalculated.", ""]
    (folder / "README.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote the benchmark to {folder}")


if __name__ == "__main__":
    main(sys.argv[1:])
