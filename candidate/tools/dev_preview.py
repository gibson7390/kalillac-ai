"""DEVELOPMENT PREVIEW: a disposable copy of the complete application, for watching changes as they are made.

Separate from everything else: its own root (/var/lib/kalillac-local-staging-dev), its own PostgreSQL cluster
(127.0.0.1:55434), database, roles and deployment id (kalillac-local-dev), synthetic settings and demo accounts,
simulated providers and payments. It never reads or touches the owner's local staging (localhost:8010, port
8011, /var/lib/kalillac-local-staging, PostgreSQL 55433) or production. Reuses tools/local_staging.py's own
provisioning, transition and simulation, with these values instead of local staging's.

Run in WSL as root, from this worktree's candidate/, with the repository's Python environment:

    python3 -B tools/dev_preview.py setup    once: build the preview (the site must be built: npm run build)
    python3 -B tools/dev_preview.py run      foreground: PostgreSQL, the application (restarted when backend
                                             Python changes), the local panel and API proxy; Ctrl-C stops all
    python3 -B tools/dev_preview.py status

and on Windows, in site/:  npx vite --config vite.preview.config.ts   (http://localhost:8020, hot reload for the site, live reload
for the chat at /app/; /api and /__local__ go to the preview's application)

Setup is the only step that creates or migrates anything, and only in the new, empty preview root. run never
migrates: if the code needs a newer schema than the preview's database, start again with a new preview.

Network isolation, per process (tests/test_dev_preview_isolation.py, tests/test_dev_preview_process_isolation.py):
  * this manager: tools/preview_guard.py, strict (this machine's loopback only, never 8010/8011/55433);
  * the application (8021) and the panel (8022), separate processes: started through tools/preview_fenced.py, which
    checks their settings (the database must be 127.0.0.1:55434) and installs the fence in the child itself:
    Python sockets, asyncio's sock_connect and libpq (psycopg) never reach 8010, 8011 or 55433 under any host.
    This holds in every lifecycle: a first setup, a resumed setup and run all start them (and setup's V1
    transition) through the same launcher and the same check of their settings (fence_children, below);
  * Vite (Node, on Windows): site/preview-fence.mjs, installed by vite.preview.config.ts in that process;
  * PostgreSQL (55434) only listens; the file workers are isolated interpreters with no network code.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import signal
import subprocess
import sys
import time

TOOLS = Path(__file__).resolve().parent
sys.path[:0] = [str(TOOLS.parent), str(TOOLS)]
import local_staging as ls  # noqa: E402
import preview_guard  # noqa: E402

DEV_ROOT = Path("/var/lib/kalillac-local-staging-dev")
SITE_PORT, APP_PORT, PANEL_PORT, PG_PORT = 8020, 8021, 8022, 55434
PROTECTED = {"root": Path("/var/lib/kalillac-local-staging"), "ports": tuple(sorted(preview_guard.PROTECTED_PORTS))}
POLL_SECONDS = 1.0


def configure(create=False):
    """Point local staging's tooling at the preview: its root, ports, names and accounts."""
    if set(PROTECTED["ports"]) & {SITE_PORT, APP_PORT, PANEL_PORT, PG_PORT}:
        ls.fail("the preview's ports overlap local staging's")
    ls.DEFAULT_ROOT = DEV_ROOT
    try:
        root = ls.owned_root(str(DEV_ROOT), create=create)
    except ls.UnsafeRoot as error:
        ls.fail(f"{error}. Nothing was changed.")
    if root is None:
        ls.fail(f"no preview yet at {DEV_ROOT}: run setup first")
    if root == PROTECTED["root"]:
        ls.fail("refusing to use local staging's own root")
    ls.ROOT = root
    ls.WEB_PORT, ls.APP_PORT, ls.PG_PORT = SITE_PORT, APP_PORT, PG_PORT
    ls.ORIGIN = f"http://localhost:{SITE_PORT}"
    ls.DEPLOYMENT = "kalillac-local-dev"
    ls.DATABASE = "kalillac_dev"
    ls.ROLES = {key: name.replace("kalillac_local_", "kalillac_dev_") for key, name in ls.ROLES.items()}
    ls.DEMO = {"free": "dev.free@kalillac-dev.test", "premium": "dev.premium@kalillac-dev.test"}
    # local_staging._http binds its default base URL (local staging's own origin) when the module loads:
    # rebind it to the preview's origin, or seeding would talk to local staging (it did once; see the guard).
    ls._http.__defaults__ = ls._http.__defaults__[:-1] + (ls.ORIGIN,)
    _guard_protected_ports()
    fence_children()
    ls.HEADER = ("# KALILLAC DEVELOPMENT PREVIEW: settings for local development on this machine only.\n"
                 "# Every allowance, budget, price and attempt ceiling below is a SYNTHETIC TEST INPUT, not an owner\n"
                 "# decision. Generated by tools/dev_preview.py.\n")
    return root


def _guard_protected_ports():
    """Refuse, in this process, any connection to local staging's ports or to anything but this machine: the
    preview must never reach the protected installation, even through a constant bound elsewhere, a redirect
    or another name for loopback. preview_guard fences every TCP connection (tests/test_dev_preview_isolation.py);
    the urlopen check below refuses such a URL before any request is built."""
    import urllib.request
    from urllib.parse import urlsplit
    preview_guard.install()
    if getattr(urllib.request.urlopen, "_kalillac_guarded", False):
        return
    real = urllib.request.urlopen

    def urlopen(request, *args, **kwargs):
        url = request.full_url if isinstance(request, urllib.request.Request) else str(request)
        parts = urlsplit(url)
        try:
            preview_guard.check(parts.hostname or "", parts.port or (443 if parts.scheme == "https" else 80))
        except preview_guard.PreviewFenceError as refused:
            raise RuntimeError(f"the development preview refused a request outside the preview: {url}") from refused
        return real(request, *args, **kwargs)
    urlopen._kalillac_guarded = True
    urllib.request.urlopen = urlopen


def setup(args):
    configure(create=True)
    if (ls.ROOT / "local.json").exists():
        # Resumable: built already (an earlier setup stopped while seeding). Finish the demo accounts.
        ls.start(args)
        if not (ls.ROOT / "demo-accounts.txt").exists():
            ls.say("7/7 synthetic demo accounts, through the real registration, sign-in and billing flows")
            ls.seed(ls.paths())
        ls.status(args)
    else:
        ls.setup(args)             # Provision, activate, build the web root, start, seed the demo accounts.
    ls.stop(None)                  # run starts it again in development mode.
    ls.say("preview ready: run `python3 -B tools/dev_preview.py run` here and `npx vite --config vite.preview.config.ts` in site/")


def _snapshot(paths):
    seen = {}
    for base in paths:
        for path in base.rglob("*.py"):
            if "tests" in path.parts or "__pycache__" in path.parts:
                continue
            try:
                seen[str(path)] = path.stat().st_mtime_ns
            except FileNotFoundError:
                continue
    return seen


CHILDREN = ("local_staging_app.py", "local_staging_web.py")
FENCED_LAUNCHER = (str(TOOLS / "preview_fenced.py"),)


def fence_children():
    """Every Python process local staging's own tooling starts for the preview (setup's and a resumed setup's
    application, panel and V1 transition, through ls.start and ls.setup) goes through the fenced launcher and
    the check of its settings, exactly as run's children do. A fence installed in this manager does not reach
    a child process: each child installs its own."""
    ls.LAUNCHER = FENCED_LAUNCHER
    ls.CHILD_ENVIRONMENT = child_environment


def child_environment(env):
    """The application's and panel's environment: checked before either starts (no setting may name local
    staging's ports, and the database must be the preview's own, on this machine, at PG_PORT), and carrying the
    database port the fenced launcher checks again inside the child."""
    env = {**env, "KALILLAC_PREVIEW_DATABASE_PORT": str(PG_PORT)}
    try:
        preview_guard.check_environment(env, database_port=PG_PORT)
    except preview_guard.PreviewFenceError as refused:
        ls.fail(f"refusing to start the preview: {refused}")
    return env


def child_command(script, *extra):
    """Every preview child runs inside the network fence (tools/preview_fenced.py installs it in that process;
    the manager's own fence does not reach a child)."""
    if script not in CHILDREN:
        raise ValueError(f"not a preview child: {script}")
    return [sys.executable, "-B", *FENCED_LAUNCHER, str(TOOLS / script), *extra]


def run(args):
    configure()
    uid, gid, _group, home = ls.identity()
    p = ls.paths()
    if not (ls.ROOT / "local.json").exists():
        ls.fail("the preview is not set up: run setup first")
    ls.pg_start(p, ls.pg_bin(home), uid, gid)
    env = child_environment(ls.service_env(p, home))
    log = open(p["state"] / "dev-preview.log", "ab")
    drop = {"user": uid, "group": gid, "extra_groups": []}

    def spawn(script, *extra):
        return subprocess.Popen(child_command(script, *extra), cwd=str(TOOLS.parent), env=env,
                                stdout=log, stderr=subprocess.STDOUT, start_new_session=True, **drop)

    def stop_child(child):
        if child.poll() is None:
            os.killpg(child.pid, signal.SIGTERM)          # Our own child: its pid and group are ours.
            try:
                child.wait(timeout=15)
            except subprocess.TimeoutExpired:
                os.killpg(child.pid, signal.SIGKILL)
                child.wait()

    app = spawn("local_staging_app.py", "--host", "127.0.0.1", "--port", str(APP_PORT))
    panel = spawn("local_staging_web.py", "--webroot", str(p["webroot"]), "--upstream",
                  f"http://127.0.0.1:{APP_PORT}", "--port", str(PANEL_PORT))
    watched = [TOOLS.parent]                               # candidate/: every backend module, tests excluded.
    before = _snapshot([w for w in watched if w.is_dir()])
    ls.say(f"DEVELOPMENT preview running: application 127.0.0.1:{APP_PORT}, panel/API 127.0.0.1:{PANEL_PORT}; "
           f"open http://localhost:{SITE_PORT} after `npx vite --config vite.preview.config.ts` in site/. Log: {p['state'] / 'dev-preview.log'}")
    stopping = []
    signal.signal(signal.SIGTERM, lambda *_: stopping.append(True))
    try:
        while not stopping:
            time.sleep(POLL_SECONDS)
            now = _snapshot([w for w in watched if w.is_dir()])
            if now != before:
                changed = sorted(k for k in set(now) | set(before) if now.get(k) != before.get(k))
                time.sleep(0.5)                            # Let an editor finish writing.
                before = _snapshot([w for w in watched if w.is_dir()])
                ls.say(f"backend change ({len(changed)} file(s), e.g. {Path(changed[0]).name}): restarting the "
                       "application")
                stop_child(app)
                app = spawn("local_staging_app.py", "--host", "127.0.0.1", "--port", str(APP_PORT))
            if app.poll() is not None:
                ls.say(f"the application exited ({app.returncode}); see {p['state'] / 'dev-preview.log'}. "
                       "Fix the code: it restarts on the next change.")
                before = _snapshot([w for w in watched if w.is_dir()])
                while not stopping and _snapshot([w for w in watched if w.is_dir()]) == before:
                    time.sleep(POLL_SECONDS)
                if not stopping:
                    before = _snapshot([w for w in watched if w.is_dir()])
                    app = spawn("local_staging_app.py", "--host", "127.0.0.1", "--port", str(APP_PORT))
    except KeyboardInterrupt:
        pass
    finally:
        for child in (app, panel):
            stop_child(child)
        ls.stop(None)
        ls.say("preview stopped")


def status(args):
    configure()
    ls.status(args)


def main(argv=None):
    if not ls._running_as_root():
        ls.fail("run as root in WSL (wsl -u root ...)")
    parser = argparse.ArgumentParser(prog="dev_preview.py")
    sub = parser.add_subparsers(dest="command", required=True)
    for name, handler in (("setup", setup), ("run", run), ("status", status)):
        sub.add_parser(name).set_defaults(handler=handler)
    args = parser.parse_args(argv)
    args.handler(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
