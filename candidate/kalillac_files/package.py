"""Office Open XML package hygiene for the Word and PowerPoint writers.

python-docx and python-pptx start every file from a starter template, and the
template's own record travels with it: a "generated by" description, its
author, its 2013 dates, an application record that names a Macintosh Office
release and a 4:3 page, a thumbnail of an empty page, and the template's
bibliography and printer settings. None of that describes the file Kalillac
made. These helpers replace it with this file's own record and date every ZIP
entry at the ZIP epoch, so the same specification always yields the same bytes.
"""
import io
from xml.sax.saxutils import escape
import zipfile

_DCTERMS = "{http://purl.org/dc/terms/}"


CORE_TEXT = 255  # The longest text a core property holds (python-docx and python-pptx refuse more).


def fitted(text, limit=CORE_TEXT):
    """Text cut at a word boundary to fit a core property, marked with an ellipsis when cut."""
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    cut = text[:limit - 1]
    return (cut[:cut.rfind(" ")] if " " in cut else cut).rstrip(" ,;:") + "…"


def own_record(core_properties, author, description=""):
    """The core properties of this file alone: its author, its description, and no template dates."""
    core_properties.comments = fitted(description)
    core_properties.last_modified_by = author
    element = core_properties._element
    for tag in ("created", "modified"):
        for found in element.findall(_DCTERMS + tag):
            element.remove(found)


def drop_relationships(relationships, *kinds):
    """Remove every relationship of the given types (the last segment of the type URI)."""
    for r_id in [r_id for r_id, rel in relationships.items() if rel.reltype.rsplit("/", 1)[-1] in kinds]:
        relationships.pop(r_id)


def application_record(package_relationships, **facts):
    """Replace the extended properties (docProps/app.xml) with Kalillac's own short record."""
    body = "".join(f"<{name}>{escape(str(value))}</{name}>" for name, value in facts.items() if value is not None)
    xml = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<Properties xmlns="http://schemas.'
           'openxmlformats.org/officeDocument/2006/extended-properties"><Application>Kalillac AI</Application>'
           f'{body}</Properties>')
    for rel in package_relationships.values():
        if rel.reltype.endswith("/extended-properties"):
            rel.target_part._blob = xml.encode("utf-8")


def fixed_dates(data):
    """The same package with every entry dated at the ZIP epoch, in the same order."""
    source = zipfile.ZipFile(io.BytesIO(data))
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as target:
        for item in source.infolist():
            entry = zipfile.ZipInfo(item.filename, date_time=(1980, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            target.writestr(entry, source.read(item.filename))
    return output.getvalue()
